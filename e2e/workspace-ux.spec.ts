const requestRow = { id: 'ux-r', folderId: 'ux-f', name: '상품 / 기본정보', method: 'POST', url: 'https://example.test/product', params: [], headers: [], bodyType: 'json', body: '{}', description: '', origin: 'manual', specState: null }
