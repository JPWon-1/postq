import { expect, test } from '@playwright/test'

for (const width of [1280, 1440]) test(`요청 변수 표: 참조·범위·인라인 저장·전체 변수·긴 값 ${width}`, async ({ page, request }) => {
  await page.setViewportSize({ width, height: 900 })
  const workspace = await (await request.post('/api/workspaces', { data: { name: `e2e-vars-${width}` } })).json()
  const previousGlobals = await (await request.get('/api/global-vars?workspaceId=*')).json()
  try {
    await request.put('/api/global-vars', { data: { workspaceId: '*', variables: [...previousGlobals, { key: 'panelGlobal', value: 'global-value', secret: false }] } })
    const folder = await (await request.post('/api/folders', { data: { workspaceId: workspace.id, name: '변수 API', sharedHeaders: [{ key: 'X-Shared', value: '{{folderToken}}', enabled: true }], sharedAuth: { type: 'bearer', token: '{{authToken}}' } } })).json()
    await request.put(`/api/folders/${folder.id}`, { data: { sharedHeaders: [{ key: 'X-Shared', value: '{{folderToken}}', enabled: true }], sharedAuth: { type: 'bearer', token: '{{authToken}}' } } })
    const env = await (await request.post('/api/environments', { data: { workspaceId: workspace.id, name: '표 환경' } })).json()
    await request.put(`/api/environments/${env.id}`, { data: { variables: ['baseUrl', 'headerVar', 'bodyVar', 'folderToken', 'authToken', 'scriptInput', 'unused'].map(key => ({ key, value: key === 'baseUrl' ? 'https://api.example.com' : key + '-value', secret: false })) } })
    const row = await (await request.post('/api/requests', { data: { folderId: folder.id, name: '표 편집', method: 'POST', url: '{{baseUrl}}/{{missing}}', headers: [{ key: 'X-Value', value: '{{headerVar}}', enabled: true }, { key: 'X-Global', value: '{{panelGlobal}}', enabled: true }, { key: 'X-Off', value: '{{disabledVar}}', enabled: false }], auth: { type: 'inherit' }, bodyType: 'json', body: '{"value":"{{bodyVar}}"}', preSteps: [{ name: 'derived', op: 'base64', input: '{{scriptInput}}' }] } })).json()
    await page.addInitScript(id => { localStorage.clear(); localStorage.setItem('ah:workspace', id) }, workspace.id)
    await page.goto(`/?req=${row.id}`)
    await page.getByLabel('실행 환경', { exact: true }).selectOption(env.id)
    await page.getByRole('button', { name: '변수', exact: true }).click()
    const panel = page.getByRole('complementary', { name: '요청 보조 패널' })
    await expect(panel.getByText('이 요청의 변수', { exact: true })).toBeVisible()
    const used = panel.getByRole('table', { name: '이 요청의 변수', exact: true })
    for (const name of ['baseUrl', 'headerVar', 'bodyVar', 'folderToken', 'authToken', 'scriptInput', 'panelGlobal', 'missing']) await expect(used.locator(`[data-variable-row="${name}"]`)).toBeVisible()
    await expect(used.locator('[data-variable-row="unused"]')).toHaveCount(0)
    await expect(used.locator('[data-variable-row="disabledVar"]')).toHaveCount(0)
    await expect(panel.locator('details')).not.toHaveAttribute('open')
    const base = used.locator('[data-variable-row="baseUrl"]')
    await base.getByRole('button', { name: '현재 환경', exact: true }).hover()
    await expect(page.getByRole('tooltip')).toHaveText('현재 환경', { timeout: 200 })
    const long = 'https://api.example.com/v1/very/long/path?x=1&detail=full'
    await base.getByRole('button', { name: 'baseUrl 값 편집' }).click()
    const input = base.getByLabel('baseUrl 값', { exact: true })
    await input.fill(long)
    expect(await input.evaluate(el => el.scrollHeight <= el.clientHeight + 2 && el.scrollWidth <= el.clientWidth + 2)).toBe(true)
    await page.screenshot({ path: `/tmp/postq-variable-panel-${width}.png` })
    await input.press('Enter')
    await expect(input).toHaveCount(0)
    const savedEnv = () => request.get(`/api/environments?workspaceId=${workspace.id}`).then(r => r.json())
    await expect.poll(async () => (await savedEnv())[0].variables.find((v: { key: string }) => v.key === 'baseUrl').value).toBe(long)
    await base.getByRole('button', { name: 'baseUrl 값 편집' }).click()
    await input.fill('cancel-me'); await input.press('Escape')
    expect((await savedEnv())[0].variables.find((v: { key: string }) => v.key === 'baseUrl').value).toBe(long)
    await page.route(`**/api/environments/${env.id}`, route => route.fulfill({ status: 409, json: { error: 'conflict' } }))
    await base.getByRole('button', { name: 'baseUrl 값 편집' }).click()
    await input.fill('keep-on-error'); await input.press('Enter')
    await expect(base.getByRole('alert')).toContainText('다른 변경')
    await expect(input).toHaveValue('keep-on-error')
    await page.unroute(`**/api/environments/${env.id}`)
    await input.press('Escape')
    const missing = used.locator('[data-variable-row="missing"]')
    await expect(missing).toContainText('현재 환경에 추가')
    await missing.getByRole('button', { name: 'missing 값 편집' }).click()
    await missing.getByLabel('missing 값', { exact: true }).fill('created')
    // 값 입력 영역에서 나가면 저장된다. 범위 select로 옮길 때는 아직 저장하지 않는다.
    await missing.getByLabel('missing 저장 범위').focus()
    expect((await savedEnv())[0].variables.some((v: { key: string }) => v.key === 'missing')).toBe(false)
    await page.getByLabel('요청 URL', { exact: true }).focus()
    await expect.poll(async () => (await savedEnv())[0].variables.find((v: { key: string }) => v.key === 'missing')?.value).toBe('created')
    await page.getByRole('button', { name: '코드 스니펫', exact: true }).click()
    await expect(page.getByTestId('live-code-snippet')).toContainText('api.example.com/v1/very/long/path')
    await expect(page.getByTestId('live-code-snippet')).toContainText('created')
    await page.getByRole('button', { name: '변수', exact: true }).click()
    await panel.locator('summary').filter({ hasText: '모든 변수' }).click()
    await expect(panel.getByRole('table', { name: '현재 환경 변수', exact: true }).locator('[data-variable-row="unused"]')).toBeVisible()
    const global = panel.getByRole('table', { name: '전역 변수', exact: true }).locator('[data-variable-row="panelGlobal"]')
    await global.getByRole('button', { name: 'panelGlobal 값 편집' }).click()
    await global.getByLabel('panelGlobal 값', { exact: true }).fill('global-updated')
    await global.getByLabel('panelGlobal 값', { exact: true }).press('Enter')
    await expect.poll(async () => (await (await request.get('/api/global-vars?workspaceId=*')).json()).find((v: { key: string }) => v.key === 'panelGlobal').value).toBe('global-updated')
    await page.screenshot({ path: `/tmp/postq-all-variables-${width}.png` })
    const secretRow = panel.getByRole('table', { name: '이 요청의 변수', exact: true }).locator('[data-variable-row="authToken"]')
    await secretRow.getByRole('button', { name: 'authToken 값 편집' }).click()
    await secretRow.getByLabel('authToken 저장 범위').selectOption('personal')
    const secret = secretRow.getByLabel('authToken 값', { exact: true })
    await secret.fill('private-panel-token')
    expect(await secret.evaluate(el => getComputedStyle(el).getPropertyValue('-webkit-text-security'))).toBe('disc')
    await secret.press('Enter')
    await expect(secretRow.getByRole('button', { name: '내 개인 값', exact: true })).toBeVisible()
    await expect(secretRow).not.toContainText('private-panel-token')
    await secretRow.getByRole('button', { name: 'authToken 보기', exact: true }).click()
    await expect(secretRow).toContainText('private-panel-token')
    await secretRow.getByRole('button', { name: 'authToken 숨기기', exact: true }).click()
    await expect(secretRow).not.toContainText('private-panel-token')
    await page.getByRole('button', { name: /^Body/ }).click()
    await expect(page.getByLabel('바디 타입', { exact: true })).toHaveValue('raw')
    await expect(page.getByLabel('본문 형식', { exact: true })).toHaveValue('json')
    const body = page.getByLabel('요청 바디', { exact: true })
    await body.fill('{"x":1}')
    await page.getByRole('button', { name: 'JSON 정리', exact: true }).click()
    await expect(body).toHaveValue(/\n/)
    await page.getByLabel('본문 형식', { exact: true }).selectOption('raw')
    await expect(body).toHaveValue(/"x": 1/)
    await page.screenshot({ path: `/tmp/postq-body-format-${width}.png` })
  } finally {
    await request.put('/api/global-vars', { data: { workspaceId: '*', variables: previousGlobals } })
    await request.delete(`/api/workspaces/${workspace.id}`)
  }
})
